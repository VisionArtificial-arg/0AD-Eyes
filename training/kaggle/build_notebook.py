"""Build the Kaggle training notebook for MOD-3 from ``training/train_yolo_seg.py``.

The notebook embeds the script verbatim (a ``%%writefile`` cell), so the repo stays the
single source and the notebook needs neither the 0AD-Eyes repo nor the package.

    python training/kaggle/build_notebook.py [--epochs N] [--model yolo11n-seg.pt] [--name v1]
        [--batch 2] [--device 0] [--cache ram]
    kaggle kernels push -p training/kaggle --accelerator NvidiaTeslaT4

The dataset (``santiagogarrote/zad-w1-yolo``) is attached through kernel-metadata.json
and mounted read-only under /kaggle/input; results land in /kaggle/working (the run's
output), zipped as ``<name>.zip`` for a one-click download.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPT = HERE.parent / "train_yolo_seg.py"


def cell(kind: str, source: str) -> dict:
    lines = source.strip("\n").splitlines(keepends=True)
    if kind == "markdown":
        return {"cell_type": "markdown", "metadata": {}, "source": lines}
    return {
        "cell_type": "code",
        "metadata": {},
        "execution_count": None,
        "outputs": [],
        "source": lines,
    }


def build(epochs: int, model: str, name: str, batch: int, device: str, cache: str) -> dict:
    cells = [
        cell(
            "markdown",
            f"""
# 0AD-Eyes MOD-3: YOLO11-seg `{name}`

Trains `{model}` on the W1 engine-fork set (`santiagogarrote/zad-w1-yolo`, split by match)
with `training/train_yolo_seg.py` from VisionArtificial-arg/0AD-Eyes, embedded below.
Generated by `training/kaggle/build_notebook.py`; edit that, not this notebook.
""",
        ),
        cell(
            "code",
            '!pip install -q "ultralytics>=8.3,<9"\n'
            "!nvidia-smi --query-gpu=name,memory.total --format=csv",
        ),
        cell("code", "%%writefile train_yolo_seg.py\n" + SCRIPT.read_text()),
        cell(
            "code",
            """
import shutil
from pathlib import Path

# Kaggle mounts attached datasets read-only under /kaggle/input, and reading the PNGs
# from there is slow (~9 MB/s). Copy to local disk; Ultralytics can then also write its
# label cache.
yamls = sorted(Path("/kaggle/input").rglob("data.yaml"))
assert yamls, "dataset not attached: add santiagogarrote/zad-w1-yolo"
LOCAL = Path("/tmp/zad-w1-yolo")
if not LOCAL.exists():
    shutil.copytree(yamls[0].parent, LOCAL)
DATA = LOCAL / "data.yaml"
print(DATA, sum(1 for _ in LOCAL.rglob("*.png")), "images")
""",
        ),
        cell(
            "code",
            f"""
CMD = (
    f"python train_yolo_seg.py --data {{DATA}} --model {model} --epochs {epochs} "
    "--batch {batch} --device {device} --cache {cache} --project /kaggle/working/runs "
    "--name {name} --workers 4"
)
!{{CMD}}
""",
        ),
        cell(
            "code",
            f"""
import json

run = Path("/kaggle/working/runs/{name}")
sidecar = json.loads((run / "sidecar.json").read_text())
print(json.dumps(sidecar.get("test_metrics", {{}}), indent=2))
shutil.make_archive("/kaggle/working/{name}", "zip", run)
print("download:", "/kaggle/working/{name}.zip")
""",
        ),
    ]
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--epochs", type=int, default=60)
    parser.add_argument("--model", default="yolo11n-seg.pt")
    parser.add_argument("--name", default="v1")
    # One T4 at batch 2: dense frames (up to ~800 objects) made the mask loss run out of
    # memory at batch 4 per GPU, and the CPU (PNG decoding, mosaics) is the bottleneck, so a
    # second GPU added no speed. The RAM cache removes the decoding.
    parser.add_argument("--batch", type=int, default=2, help="total over all GPUs (default 2)")
    parser.add_argument("--device", default="0")
    parser.add_argument("--cache", choices=("none", "ram", "disk"), default="ram")
    args = parser.parse_args()
    out = HERE / "mod3_train.ipynb"
    out.write_text(
        json.dumps(
            build(args.epochs, args.model, args.name, args.batch, args.device, args.cache), indent=1
        )
        + "\n"
    )
    print(f"wrote {out} ({args.model}, {args.epochs} epochs, run {args.name})")


if __name__ == "__main__":
    main()
